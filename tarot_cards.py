# --- Функция: получить значение карты ---
def get_card_meaning(card_name):
    """
    Возвращает значение карты Таро по её названию.
    """
    card_data = TAROT_CARDS.get(card_name.strip())
    if isinstance(card_data, dict):
        return card_data.get("meaning_upright", "❌ Значение для этой карты не найдено")
    elif isinstance(card_data, str):
        return card_data
    else:
        return "❌ Значение для этой карты не найдено"

